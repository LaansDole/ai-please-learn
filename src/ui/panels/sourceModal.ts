import type { StoredConcept } from '../../gen/library';
import { h } from '../dom';

/** Read-only view of a generated concept: its prompt, metadata and module. Escape or the button closes it. */
export function showSource(c: StoredConcept): void {
  const dialog = h('dialog', { class: 'source-modal', testid: 'source-modal', 'aria-label': `Source of ${c.name}` },
    h('div', { class: 'modal-head' },
      h('h2', null, c.name),
      h('button', { type: 'button', testid: 'source-close', onclick: () => dialog.close() }, 'Close')),
    h('p', { class: 'muted' }, `Generated by ${c.model} on ${new Date(c.createdAt).toLocaleDateString()}. Read-only.`),
    h('h3', null, 'Prompt'), h('pre', null, c.prompt || '(none: pasted or imported)'),
    h('h3', null, 'Metadata'), h('pre', null, JSON.stringify(c.meta, null, 2)),
    h('h3', null, 'Module'), h('pre', null, c.source));
  dialog.addEventListener('close', () => dialog.remove());
  document.body.append(dialog);
  dialog.showModal();
}
